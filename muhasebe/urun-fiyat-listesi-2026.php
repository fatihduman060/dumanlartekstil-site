function urun_fiyat_listesi_2026_import(PDO $pdo): void
{
    if (setting_get('urun_fiyat_listesi_2026_v1', '0') === '1') return;

    $byBarcode = $pdo->prepare("SELECT id FROM offer_products WHERE TRIM(COALESCE(barcode,''))=? ORDER BY id LIMIT 1");
    $byArticle = $pdo->prepare('SELECT id FROM offer_products WHERE name LIKE ? ORDER BY id LIMIT 1');
    $byName = $pdo->prepare('SELECT id FROM offer_products WHERE name=? ORDER BY id LIMIT 1');
    $update = $pdo->prepare("UPDATE offer_products SET barcode=?, list_unit_price=?, is_active=1, updated_at=? WHERE id=?");
    $insert = $pdo->prepare('INSERT INTO offer_products (barcode,name,product_type,default_unit_price,list_unit_price,is_active,created_at,updated_at) VALUES (?,?,?,?,?,1,?,?)');
    $now = now();

    $startedTransaction = !$pdo->inTransaction();
    if ($startedTransaction) $pdo->beginTransaction();
    try {
        foreach (urun_fiyat_listesi_2026() as $product) {
            [$barcode,$article,$name,$price,$season] = $product;
            $id = 0;
            $byBarcode->execute([$barcode]);
            $id = (int)($byBarcode->fetchColumn() ?: 0);
            if ($id <= 0) {
                $byArticle->execute([$article . ' %']);
                $id = (int)($byArticle->fetchColumn() ?: 0);
            }
            if ($id <= 0) {
                $byName->execute([$name]);
                $id = (int)($byName->fetchColumn() ?: 0);
            }
            if ($id > 0) {
                $update->execute([$barcode,$price,$now,$id]);
            } else {
                $insert->execute([$barcode,$article . ' ' . $name,$season,0,$price,$now,$now]);
            }
        }
        $pdo->prepare("INSERT INTO settings (key,value,updated_at) VALUES (?,?,?)
            ON CONFLICT(key) DO UPDATE SET value=excluded.value,updated_at=excluded.updated_at")
            ->execute(['urun_fiyat_listesi_2026_v1','1',$now]);
        if ($startedTransaction) $pdo->commit();
    } catch (Throwable $e) {
        if ($startedTransaction && $pdo->inTransaction()) $pdo->rollBack();
        throw $e;
    }
}
